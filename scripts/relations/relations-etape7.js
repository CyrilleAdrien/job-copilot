// Lancer depuis la racine : WEB_URL=http://localhost:3000 API_URL=http://localhost:8000 node scripts/relations/relations-etape7.js
const WEB = process.env.WEB_URL ?? 'http://localhost:3000';
const API = process.env.API_URL ?? 'http://localhost:8000';
const { chromium } = require('playwright');
const out = (process.env.SHOTS_DIR ?? 'relations-shots') + '/';
const ok = (c, m) => { console.log((c ? 'OK  ' : 'FAIL') + ' ' + m); if (!c) process.exitCode = 1; };
const api = (p, o) => fetch(API + '/api/applications' + p, o).then(r => r.status === 204 ? null : r.json());
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
  await p.goto(WEB + '/candidatures'); await p.waitForTimeout(2500);
  const panel = p.locator('section[aria-label="Candidatures à finaliser"] > button');
  ok(await panel.getAttribute('aria-expanded') === 'false', 'À finaliser replié par défaut');
  const favs = p.getByRole('button', { name: 'Créer la candidature' });
  const n0 = await favs.count(); ok(n0 >= 1, `favoris sans candidature dans le Kanban : ${n0}`);
  await p.screenshot({ path: out + 'e7e-kanban.png' });
  const before = (await api('/applications')).length;
  await favs.first().click(); await p.waitForTimeout(1200);
  ok(await favs.count() === n0 - 1, 'le favori quitte la liste après création');
  const apps = await api('/applications'); ok(apps.length === before + 1, 'une seule candidature créée');
  const created = apps.find(a => a.offer_id === 21 || a.offer_id === 22);
  ok(created && created.status === 'draft', `candidature ${created && created.offer_id} au statut À envoyer`);
  ok(!(await p.locator('section[aria-label="Candidatures à finaliser"]').textContent()).includes(created.title), 'favori sans document : pas dans À finaliser');
  await p.goto(WEB + '/offres'); await p.waitForTimeout(2000);
  await p.getByRole('radio', { name: 'Favoris' }).click().catch(() => p.getByText('Favoris', { exact: true }).first().click());
  await p.waitForTimeout(1500);
  const card = p.locator('article', { hasText: created.title }).first();
  ok(/À envoyer/.test(await card.textContent()), 'badge À envoyer sur la carte de l\'offre en favori');
  await api('/applications/' + created.id, { method: 'DELETE' });
  await p.goto(WEB + '/candidatures'); await p.waitForTimeout(2000);
  ok(await p.getByRole('button', { name: 'Créer la candidature' }).count() === n0, 'après suppression, le favori revient dans À envoyer');
  await panel.click(); await p.waitForTimeout(500);
  const row = p.locator('section[aria-label="Candidatures à finaliser"] li').first();
  const title = (await row.locator('span').first().textContent()).trim();
  await row.getByRole('button', { name: 'Envoyée' }).click(); await p.waitForTimeout(1200);
  const sent = (await api('/applications')).find(a => a.title === title && a.status === 'sent');
  ok(!!sent, `« Envoyée » depuis À finaliser passe ${title} au statut Envoyée`);
  await p.goto(WEB + '/offres/' + sent.offer_id); await p.waitForTimeout(2000);
  ok(/Envoyée/.test(await p.locator('main').textContent()), 'la fiche d\'offre affiche Envoyée');
  await api('/applications/' + sent.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ status: 'draft' }) });
  await p.goto(WEB + '/candidatures'); await p.waitForTimeout(2000);
  await p.getByRole('button', { name: 'Filtres' }).click(); await p.waitForTimeout(500);
  await p.screenshot({ path: out + 'e7e-filtres.png' });
  await p.keyboard.press('Escape');
  await p.getByRole('dialog').waitFor({ state: 'detached' }).catch(() => {});
  ok(await p.getByRole('dialog').count() === 0, 'Échap ferme le panneau des filtres');
  await b.close();
})();
